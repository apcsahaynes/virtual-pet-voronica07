public class Sleep {
    private String name;
    private int energyIncrease;
    
    public Sleep(String name, int energyIncrease){
     this.name = name;
     this.energyIncrease = energyIncrease;
    }
    public String getName(){
       return this.name;
    }
       
    public int getEnergyIncrease(){
       return this.energyIncrease;
}
}
